#!/bin/sh
# libbar.c: two families of N small functions, bar_a_* (run only by process
# A) and bar_b_* (run only by B), each numbering many dense blocks of its own.
N=${1:-400}
echo '/* Generated by genbar.sh. */'
for f in a b; do
  i=0
  while [ $i -lt $N ]; do
    echo "int bar_${f}_$i(int x) { int s = $i; for (int j = 0; j < x; j++) s = s * $((i % 13 + 2)) + j$( [ $f = b ] && echo ' + 1'); return s; }"
    i=$((i + 1))
  done
  echo "int bar_${f}_all(int x) { int s = 0;"
  i=0
  while [ $i -lt $N ]; do echo "  s ^= bar_${f}_$i(x);"; i=$((i + 1)); done
  echo "  return s; }"
done
