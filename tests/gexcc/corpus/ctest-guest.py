#!/usr/bin/env python3
"""A CTest suite as one shell script for the guest (recipes.sh: ctest_guest).

    ctest-guest.py BUILD_DIR > script.sh

Reads `ctest --show-only=json-v1` and writes a busybox-sh script that runs
each test in its working directory and prints `PASS: name` or `FAIL: name`,
so the whole suite runs inside one gexc instead of one host gexc per test.
The CMAKE_CROSSCOMPILING_EMULATOR (gexcc-run) prefix is dropped: inside the
guest a gexcc program runs directly. Honoured properties: WORKING_DIRECTORY,
WILL_FAIL, PASS_REGULAR_EXPRESSION, FAIL_REGULAR_EXPRESSION, ENVIRONMENT,
DISABLED, TIMEOUT."""
import json, shlex, subprocess, sys

b = sys.argv[1]
info = json.loads(subprocess.run(['ctest', '--show-only=json-v1'], cwd=b, capture_output=True, text=True, check=True).stdout)
out = ['#!/bin/sh', '# generated by ctest-guest.py', 'run() {']
out.append('  n=$1; shift; wd=$1; shift; mode=$1; shift; pat=$1; shift; fpat=$1; shift')
out.append('  o=$( cd "$wd" && "$@" 2>&1 ); r=$?')
out.append('  ok=0; [ $r -eq 0 ] && ok=1')
out.append('  [ -n "$pat" ] && { printf "%s" "$o" | grep -Eq -- "$pat" && ok=1 || ok=0; }')
out.append('  [ -n "$fpat" ] && printf "%s" "$o" | grep -Eq -- "$fpat" && ok=0')
out.append('  [ "$mode" = willfail ] && ok=$((1 - ok))')
out.append('  if [ $ok = 1 ]; then echo "PASS: $n"; else echo "FAIL: $n"; printf "%s\\n" "$o" | tail -20; fi')
out.append('}')
for t in info.get('tests', []):
    cmd = t.get('command')
    if not cmd:
        continue
    if cmd[0].endswith('gexcc-run'):
        cmd = cmd[1:]
    props = {p['name']: p['value'] for p in t.get('properties', [])}
    if props.get('DISABLED'):
        out.append('echo %s' % shlex.quote('SKIP: ' + t['name']))
        continue
    wd = props.get('WORKING_DIRECTORY', b)
    mode = 'willfail' if props.get('WILL_FAIL') else 'normal'
    pat = '|'.join(props.get('PASS_REGULAR_EXPRESSION', []) or [])
    fpat = '|'.join(props.get('FAIL_REGULAR_EXPRESSION', []) or [])
    env = ' '.join(shlex.quote(e) for e in props.get('ENVIRONMENT', []) or [])
    tmo = int(float(props.get('TIMEOUT', 1500)))
    pre = ('env %s ' % env if env else '') + 'timeout %d ' % tmo
    out.append('run %s %s %s %s %s %s%s' % (shlex.quote(t['name']), shlex.quote(wd), mode, shlex.quote(pat),
                                         shlex.quote(fpat), pre, ' '.join(shlex.quote(c) for c in cmd)))
print('\n'.join(out))
