#!/usr/bin/env python3
"""Generate Mono's interp-to-native wrappers for wasm64 (gex).

A cookie names the callee's wasm signature: the return, then each argument, with
I = i32, L = i64 (pointer-sized values included on wasm64), F = f32, D = f64, V = void.
Every cookie up to MAX_FULL arguments is generated; longer ones come from the extra list and,
with --types-from WASM, from every function type of a first link of the provider (a native
callee in the provider has one of them), so build.sh links twice.
On a 64-bit runtime each integer argument (I or L) takes one slot of margs->iargs.

  gen-m2n.py [EXTRA] [--types-from WASM] > m2n.c"""
import itertools, sys

MAX_FULL = 4
CT = {'V': 'void', 'I': 'int32_t', 'L': 'int64_t', 'F': 'float', 'D': 'double'}

def cookies(extra):
    out = set()
    for n in range(MAX_FULL + 1):
        for ret in 'VILFD':
            for args in itertools.product('ILFD', repeat=n):
                out.add(ret + ''.join(args))
    out |= set(extra)
    return sorted(out)

def wrapper(c):
    ret, args = c[0], c[1:]
    it = ft = 0
    vals = []
    for a in args:
        if a == 'I':
            vals.append(f"mono_wasm_interp_method_args_get_iarg (margs, {it})"); it += 1
        elif a == 'L':
            vals.append(f"mono_wasm_interp_method_args_get_larg (margs, {it})"); it += 1
        elif a == 'F':
            vals.append(f"mono_wasm_interp_method_args_get_farg (margs, {ft})"); ft += 1
        else:
            vals.append(f"mono_wasm_interp_method_args_get_darg (margs, {ft})"); ft += 1
    params = ', '.join(CT[a] for a in args) or 'void'
    call = f"(({CT[ret]} (*)({params}))fn)({', '.join(vals)})"
    body = f"\t{call};" if ret == 'V' else f"\t*({CT[ret]} *)mono_wasm_interp_method_args_get_retval (margs) = {call};"
    return f"static void m2n_{c} (void *fn, InterpMethodArguments *margs)\n{{\n{body}\n}}\n"

def leb(d, i):
    r = sh = 0
    while True:
        b = d[i]; i += 1
        r |= (b & 0x7f) << sh; sh += 7
        if b < 0x80:
            return r, i

def wasm_cookies(path):
    """Cookies for the function types in a wasm module's type section."""
    d = open(path, 'rb').read()
    VT = {0x7f: 'I', 0x7e: 'L', 0x7d: 'F', 0x7c: 'D'}
    i, out = 8, set()
    while i < len(d):
        sid = d[i]; size, i = leb(d, i + 1)
        if sid == 1:
            n, j = leb(d, i)
            for _ in range(n):
                if d[j] != 0x60:
                    raise SystemExit(f"{path}: unexpected type form {d[j]:#x}")
                np_, j = leb(d, j + 1); ps = d[j:j + np_]; j += np_
                nr, j = leb(d, j); rs = d[j:j + nr]; j += nr
                if nr <= 1 and all(b in VT for b in ps + rs):
                    out.add((VT[rs[0]] if nr else 'V') + ''.join(VT[b] for b in ps))
            return out
        i += size
    return out

def main():
    args = sys.argv[1:]
    types = set()
    if '--types-from' in args:
        k = args.index('--types-from'); types = wasm_cookies(args[k + 1]); del args[k:k + 2]
    extra = [l.strip() for l in open(args[0]) if l.strip() and not l.startswith('#')] if args else []
    extra += [c for c in types if len(c) <= 24]
    cs = cookies(extra)
    print("/* GENERATED by gen-m2n.py: Mono interp-to-native wrappers for wasm64 (gex). */")
    print("#include <stdint.h>\n#include <string.h>\n#include <stdlib.h>")
    print("""typedef struct _InterpMethodArguments InterpMethodArguments;
int mono_wasm_interp_method_args_get_iarg (InterpMethodArguments *margs, int i);
int64_t mono_wasm_interp_method_args_get_larg (InterpMethodArguments *margs, int i);
float mono_wasm_interp_method_args_get_farg (InterpMethodArguments *margs, int i);
double mono_wasm_interp_method_args_get_darg (InterpMethodArguments *margs, int i);
void **mono_wasm_interp_method_args_get_retval (InterpMethodArguments *margs);""")
    for c in cs:
        print(wrapper(c))
    print("typedef struct { const char *sig; void *fn; } M2N;")
    print("static const M2N m2n_table[] = {")
    for c in cs:
        print(f'\t{{"{c}", (void *)m2n_{c}}},')
    print("};")
    print("""static int m2n_cmp (const void *k, const void *e) { return strcmp ((const char *)k, ((const M2N *)e)->sig); }
void *gex_mono_interp_to_native (char *cookie)
{
	const M2N *m = bsearch (cookie, m2n_table, sizeof m2n_table / sizeof m2n_table[0], sizeof m2n_table[0], m2n_cmp);
	return m ? m->fn : NULL;
}""")

main()
