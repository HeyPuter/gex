#!/usr/bin/env python3
"""Generate gex F_body adapters for Mono's embedding API (docs/unity-dotnet.md).

Reads the MONO_API_FUNCTION(ret, name, (args)) declarations of upstream Mono's
public headers (src/native/public/mono/*/details/*-functions.h) and writes, for
each, `gexp_<name>`: an F_body that reads the arguments the guest's calling
convention passed (SysV x86-64 or Win64), calls the function, writes the result
and returns. Names in --skip are written by hand (gexmono.c).

  gen-adapters.py --abi sysv|win64 [--skip FILE] HEADER... > adapters.c
"""
import argparse, re, sys

INT_TYPES = {
    'int', 'unsigned', 'unsigned int', 'long', 'unsigned long', 'short', 'unsigned short', 'char', 'unsigned char',
    'signed char', 'mono_bool', 'mono_byte', 'mono_unichar2', 'mono_unichar4', 'int32_t', 'uint32_t', 'int64_t',
    'uint64_t', 'int16_t', 'uint16_t', 'int8_t', 'uint8_t', 'size_t', 'ssize_t', 'intptr_t', 'uintptr_t',
    'uint32_t', 'gboolean', 'guint32', 'gint32', 'guint64', 'gint64', 'guint16', 'guint8', 'mono_array_size_t',
    'gsize', 'uint', 'int64_t', 'MonoGCHandle', 'mono_array_lower_bound_t',
}
FLOAT_TYPES = {'float', 'double'}

def norm(t):
    t = re.sub(r'\bconst\b|\bvolatile\b|\bMONO_RT_EXTERNAL_ONLY\b|\bMONO_RT_MANAGED_ATTR\b', ' ', t)
    return re.sub(r'\s+', ' ', t).strip()

def kind(t, enums):
    n = norm(t)
    if '*' in n or '(' in n:
        return 'p'
    if n in FLOAT_TYPES:
        return n
    if n == 'void':
        return 'v'
    if n in INT_TYPES or n in enums or n.startswith('Mono') and n.endswith(('Type', 'Flags', 'Status', 'Mode', 'Kind', 'Options', 'Event', 'Policy', 'Format', 'Id', 'Level')):
        return 'i'
    return None

def split_params(s):
    s = s.strip()
    if s in ('', 'void'):
        return []
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    out.append(cur)
    return [p.strip() for p in out]

def param_type(p):
    # drop the name: the last identifier, unless the type is a function pointer
    if '(' in p:
        return p
    m = re.match(r'^(.*?)([A-Za-z_][A-Za-z0-9_]*)\s*(\[\s*\])?$', p)
    if not m or not m.group(1).strip():
        return p
    t = m.group(1)
    if m.group(3):
        t += '*'
    return t

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--abi', choices=['sysv', 'win64'], required=True)
    ap.add_argument('--skip')
    ap.add_argument('--have', help='file of symbols the runtime build defines; others get no adapter')
    ap.add_argument('headers', nargs='+')
    a = ap.parse_args()
    skip = set()
    if a.skip:
        skip = {l.split('#')[0].strip() for l in open(a.skip)} - {''}
    have = None
    if a.have:
        have = {l.strip() for l in open(a.have)} - {''}
    text = ''.join(open(h).read() for h in a.headers)
    enums = set(re.findall(r'}\s*(Mono[A-Za-z0-9_]*)\s*;', text))
    decls = re.findall(r'MONO_API_FUNCTION\((.*?),\s*(mono_[a-z0-9_]+)\s*,\s*\((.*?)\)\)\s*$', text, re.M)
    print('/* GENERATED by gen-adapters.py (--abi %s): adapters for Mono\'s embedding API. */' % a.abi)
    print('#include "gexmono-adapters.h"\n')
    names, skipped = [], []
    argf = 'gexp_arg' if a.abi == 'sysv' else 'gexp_arg_win64'
    for ret, name, params in decls:
        if name in skip or name in names:
            continue
        if have is not None and name not in have:
            skipped.append(name)
            continue
        rk = kind(ret, enums)
        ps = [param_type(p) for p in split_params(params)]
        ks = [kind(p, enums) for p in ps]
        if rk is None or None in ks:
            skipped.append(name)
            continue
        args, ni, nf = [], 0, 0
        for i, (p, k) in enumerate(zip(ps, ks)):
            if a.abi == 'win64':
                pos = i
                if k in FLOAT_TYPES:
                    args.append('(%s)GEXP_XMM_%s(ctx, %d)' % (p, 'D' if k == 'double' else 'F', pos) if pos < 4 else None)
                elif k == 'p':
                    args.append('(%s)(uintptr_t)%s(ctx, %d)' % (p, argf, pos))
                else:
                    args.append('(%s)%s(ctx, %d)' % (p, argf, pos))
            else:
                if k in FLOAT_TYPES:
                    args.append('(%s)GEXP_XMM_%s(ctx, %d)' % (p, 'D' if k == 'double' else 'F', nf) if nf < 8 else None)
                    nf += 1
                elif k == 'p':
                    args.append('(%s)(uintptr_t)%s(ctx, %d)' % (p, argf, ni)); ni += 1
                else:
                    args.append('(%s)%s(ctx, %d)' % (p, argf, ni)); ni += 1
        if None in args:
            skipped.append(name)
            continue
        call = '%s (%s)' % (name, ', '.join(args))
        if rk == 'v':
            body = '\t%s;' % call
        elif rk in FLOAT_TYPES:
            body = '\tGEXP_RET_%s(ctx, %s);' % ('F64' if rk == 'double' else 'F32', call)
        elif rk == 'p':
            body = '\tGEXP_RET_U64(ctx, (uint64_t)(uintptr_t)%s);' % call
        else:
            body = '\tGEXP_RET_U64(ctx, (uint64_t)%s);' % call
        print('GEXP_SYSV(gexp_%s)\n{\n\tgexp_enter(ctx);\n%s\n\treturn gexp_return(ctx, ret);\n}\n' % (name, body))
        names.append(name)
    print('__attribute__((used)) gexp_body_t const gexmono_generated_adapters[] = {')
    for n in names:
        print('\tgexp_%s,' % n)
    print('\t0\n};')
    sys.stderr.write('gen-adapters: %d adapters, %d skipped: %s\n' % (len(names), len(skipped), ' '.join(skipped)))

main()
