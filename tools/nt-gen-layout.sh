#!/usr/bin/env bash
# Generate crates/gex-kernel/src/nt/layout.rs from Wine's headers.
#
#   tools/nt-gen-layout.sh WINE_SRC > crates/gex-kernel/src/nt/layout.rs
#
# Each field in tools/nt-layout.list is measured with offsetof() by MinGW for
# (a type spelled struct_NAME is Wine's `struct NAME`)
# x86-64 and i686 against WINE_SRC/include (the pinned Wine release,
# docs/nt-layer.md §4), so the layouts are Wine's own, not transcribed.
set -euo pipefail
W=$1
HERE=$(cd "$(dirname "$0")" && pwd)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

{
    cat <<'C'
#include <stdarg.h>
#include "ntstatus.h"
#define WIN32_NO_STATUS
#include "windef.h"
#include "winbase.h"
#include "winternl.h"
#include "ddk/wdm.h"
#include "winuser.h"
#include "wingdi.h"
#include "ntuser.h"
#include "ntgdi.h"
#include <stddef.h>
C
    grep -v '^#' "$HERE/nt-layout.list" | grep -v '^$' | while read -r t f _; do
        n=$(echo "$f" | tr '.[]' '___')
        echo "const unsigned int gexoff__${t}__${n} = offsetof(${t/#struct_/struct }, $f);"
    done
    grep -v '^#' "$HERE/nt-layout.list" | grep -v '^$' | awk '{print $1}' | sort -u | while read -r t; do
        echo "const unsigned int gexsize__${t} = sizeof(${t/#struct_/struct });"
    done
    echo "const unsigned int gexsize__CONTEXT = sizeof(CONTEXT);"
} >"$TMP/l.c"

gen() { # compiler
    "$1" -nostdinc -I"$W/include" -I"$W/include/msvcrt" -D__WINESRC__ -D_WIN32 -S "$TMP/l.c" -o - |
        awk '/^_?gex(off|size)__/ { sub(":", "", $1); sub("^_", "", $1); name=$1; getline; print name, ($1 == ".space" || $1 == ".zero") ? 0 : $2 }'
}

emit() { # module-name compiler
    echo "pub mod $1 {"
    gen "$2" | python3 -c '
import sys, collections
mods = collections.OrderedDict()
for line in sys.stdin:
    name, val = line.split()
    kind, rest = name.split("__", 1)
    t, _, f = rest.partition("__")
    mods.setdefault(t.lower(), []).append(("SIZEOF" if kind == "gexsize" else f.upper(), int(val)))
for t, fields in mods.items():
    print(f"    pub mod {t} {{")
    for f, v in fields:
        print(f"        pub const {f}: u64 = {v:#x};")
    print("    }")
'
    echo "}"
}

echo "// Generated by tools/nt-gen-layout.sh from Wine 11.15's headers; do not edit."
echo "#![allow(dead_code)]"
echo "/// PE32+ (x86-64) layouts."
emit x64 x86_64-w64-mingw32-gcc
echo "/// PE32 (i386) layouts."
emit x86 i686-w64-mingw32-gcc
