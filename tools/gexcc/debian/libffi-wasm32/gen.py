#!/usr/bin/env python3
"""ffi_call's trampolines for gexcc's wasm32 libffi backend (ffi.c here).

A wasm `call_indirect` names the callee's exact signature, so calling a
function pointer whose signature is known only at run time needs one
compiled call site per signature. This writes them: one function per
(return, parameters) over the wasm value types i32 (I), i64 (J), f32 (F),
f64 (D), plus void (V) for the return, and a sorted table ffi.c searches.

Covered: every combination of up to 4 parameters; I/D and I/J up to 7; I/J/D up
to 5; all-I up to 24. Anything else returns FFI_BAD_TYPEDEF from ffi_prep_cif.
"""
import itertools, sys

def sigs():
    s = set()
    def add(types, n):
        for k in range(n + 1):
            for p in itertools.product(types, repeat=k):
                s.add(''.join(p))
    add('IJFD', 4)
    add('ID', 7)
    add('IJ', 7)
    add('IJD', 5)
    for k in range(25):
        s.add('I' * k)
    return s

CT = {'I': 'int32_t', 'J': 'int64_t', 'F': 'float', 'D': 'double', 'V': 'void'}

def arg(t, k):
    if t == 'I': return f'(int32_t)a[{k}]'
    if t == 'J': return f'(int64_t)a[{k}]'
    if t == 'F': return f'*(const float *)&a[{k}]'
    return f'*(const double *)&a[{k}]'

def main():
    out = sys.stdout
    out.write('/* generated by tools/gexcc/debian/libffi-wasm32/gen.py */\n')
    rows = []
    for p in sorted(sigs()):
        for r in 'VIJFD':
            key = r + p
            ps = ', '.join(CT[t] for t in p) or 'void'
            call = f'(({CT[r]} (*)({ps}))fn)({", ".join(arg(t, k) for k, t in enumerate(p))})'
            body = f'{call};' if r == 'V' else f'*({CT[r]} *)ret = {call};'
            out.write(f'static void t_{key}(void (*fn)(void), const uint64_t *a, void *ret) {{ (void)a; (void)ret; {body} }}\n')
            rows.append(key)
    rows.sort()
    out.write('static const struct tramp { const char *sig; tramp_fn fn; } tramps[] = {\n')
    for k in rows:
        out.write(f'  {{"{k}", t_{k}}},\n')
    out.write('};\n')

main()
