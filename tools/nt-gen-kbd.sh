#!/usr/bin/env bash
# Generate crates/gex-kernel/src/nt/user/kbdus.rs: Windows' US keyboard
# layout as win32u has it (Wine's kbdus_tables in dlls/win32u/input.c),
# flattened into the lookup arrays the NT layer uses.
#
#   tools/nt-gen-kbd.sh WINE_SRC > crates/gex-kernel/src/nt/user/kbdus.rs
#
# The tables are compiled from Wine's own source with MinGW and dumped, so
# they are Wine's, not transcribed.
set -euo pipefail
W=$1
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
IN=$W/dlls/win32u/input.c
{
    echo '#include <stdio.h>'
    echo '#include <string.h>'
    echo '#include "windef.h"'
    echo '#include "winbase.h"'
    echo '#include "winuser.h"'
    echo '#include "kbd.h"'
    echo '#define ARRAY_SIZE(x) (sizeof(x) / sizeof((x)[0]))'
    sed -n '/^static const WCHAR escW\[\]/,/^static LONG clipping_cursor/p' "$IN" | sed '$d'
    sed -n '/^static void kbd_tables_init_vsc2vk/,/^static UINT kbd_tables_get_mod_bits/p' "$IN" | sed '$d'
    cat <<'C'
int main(void)
{
    USHORT vsc2vk[0x300];
    BYTE vk2char[0x100];
    WCHAR shifted[0x100] = {0};
    const VK_TO_WCHAR_TABLE *table;
    const VK_TO_WCHARS1 *entry;
    int i;
    kbd_tables_init_vsc2vk( &kbdus_tables, vsc2vk );
    kbd_tables_init_vk2char( &kbdus_tables, vk2char );
    for (table = kbdus_tables.pVkToWcharTable; table->pVkToWchars; table++)
        for (entry = table->pVkToWchars; entry->VirtualKey; entry = NEXT_ENTRY(table, entry))
            if (!(entry->VirtualKey & ~0xff) && table->nModifications > 1)
                shifted[entry->VirtualKey] = entry->wch[1];
    printf("// Generated by tools/nt-gen-kbd.sh from Wine's dlls/win32u/input.c; do not edit.\n\n");
    printf("/// Scan code (0x100 + for E0, 0x200 + for E1) to virtual key, with the\n/// KBDEXT and other flag bits above the low byte.\npub const VSC2VK: [u16; 0x300] = [");
    for (i = 0; i < 0x300; i++) printf("%s%#x,", i % 12 ? " " : "\n    ", vsc2vk[i]);
    printf("\n];\n\n/// Virtual key to its unshifted character.\npub const VK2CHAR: [u8; 0x100] = [");
    for (i = 0; i < 0x100; i++) printf("%s%#x,", i % 16 ? " " : "\n    ", vk2char[i]);
    printf("\n];\n\n/// Virtual key to its shifted character.\npub const VK2SHIFTED: [u16; 0x100] = [");
    for (i = 0; i < 0x100; i++) printf("%s%#x,", i % 16 ? " " : "\n    ", shifted[i]);
    printf("\n];\n");
    return 0;
}
C
} > "$TMP/kbd.c"
x86_64-w64-mingw32-gcc -w -I "$W/include" -o "$TMP/kbd.exe" "$TMP/kbd.c"
# Run the dumper: it only prints, so any way to run a PE will do.
if command -v gexc >/dev/null 2>&1; then gexc run "$TMP/kbd.exe"; else wine "$TMP/kbd.exe"; fi | tr -d '\r'
