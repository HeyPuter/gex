#!/usr/bin/env python3
"""Generate gex-kernel/src/nt/sysno.rs from Wine's syscall tables.

    tools/nt-gen-sysno.py WINE_SRC > crates/gex-kernel/src/nt/sysno.rs

WINE_SRC is a checkout of the pinned Wine release (docs/nt-layer.md §8). The
ids are identical in Wine's 32- and 64-bit tables; the 64-bit table lacks the
NtWow64* calls. The 32-bit argument sizes (bytes of stdcall arguments) come
along because the i386 ABI reads its arguments off the stack.
"""
import re, sys

src = sys.argv[1]
pat = re.compile(r"SYSCALL_ENTRY\w*\(\s*(0x[0-9a-f]+),\s*(\w+),\s*(\d+)\s*\)")

def tables(path):
    t = open(path).read()
    a, rest = t.split("#define ALL_SYSCALLS \\")
    b = rest.split("#else")[0]
    t32 = [(int(i, 16), n, int(s)) for i, n, s in pat.findall(a)]
    t64 = {n for _, n, _ in pat.findall(b)}
    return t32, t64

out = ["// Generated by tools/nt-gen-sysno.py from Wine 11.15; do not edit.",
       "#![allow(non_upper_case_globals, dead_code)]", ""]
for label, path, base in [("ntdll", "dlls/ntdll/ntsyscalls.h", 0),
                          ("win32u", "dlls/win32u/win32syscalls.h", 0x1000)]:
    t32, t64 = tables(f"{src}/{path}")
    t32.sort()
    ids = [i for i, _, _ in t32]
    assert ids == list(range(base, base + len(ids))), f"{label}: ids are not dense"
    out.append(f"/// `{label}`'s syscalls, numbered from {base:#x}.")
    out.append(f"pub mod {label} {{")
    for i, n, _ in t32:
        out.append(f"    pub const {n}: u32 = {i:#06x};")
    out.append("}")
    out.append(f"/// `(name, 32-bit argument bytes, present in the 64-bit table)`, indexed by id - {base:#x}.")
    out.append(f"pub const {label.upper()}_TABLE: [(&str, u16, bool); {len(t32)}] = [")
    for i, n, s in t32:
        out.append(f"    (\"{n}\", {s}, {'true' if n in t64 else 'false'}),")
    out.append("];")
    out.append("")
print("\n".join(out))
