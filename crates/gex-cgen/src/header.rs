//! `gex_abi.h`: the C view of `gex-abi`, generated from the crate itself so
//! the two cannot drift. Everything a generated C file needs is here: the
//! context offsets, the address-space constants, the host imports, and the
//! memory and floating-point helpers whose semantics must match tier-1's.

use gex_abi::{ctx, imports, IMPORT_MODULE};
use std::fmt::Write;

/// The header's text.
pub fn header() -> String {
    let mut h = String::new();
    let w = &mut h;
    let _ = writeln!(w, "/* Generated by gex-cgen from gex-abi. Do not edit. */");
    let _ = writeln!(w, "#ifndef GEX_ABI_H\n#define GEX_ABI_H");
    let _ = writeln!(w, "#include <stdint.h>\n#include <wasm_simd128.h>\n");
    let _ = writeln!(w, "#define GEX_X86 {}", gex_abi::X86 as u32);
    let _ = writeln!(w, "#define GEX_INST_ALIGN {}u", gex_abi::INST_ALIGN);
    let _ = writeln!(w, "#define GEX_SYSCALL_INST_BYTES {}u", gex_abi::SYSCALL_INST_BYTES);
    let _ = writeln!(w, "#define GEX_GUEST_LIMIT 0x{:x}ull", gex_abi::GUEST_LIMIT);
    let _ = writeln!(w, "#define GEX_POISON_ADDR 0x{:x}u", gex_abi::POISON_ADDR);
    let _ = writeln!(w, "#define GEX_DISPATCH_DIR 0x{:x}u", gex_abi::DISPATCH_DIR);
    let _ = writeln!(w, "#define GEX_DISPATCH_PAGE 0x{:x}u", gex_abi::DISPATCH_PAGE);
    let _ = writeln!(w, "#define GEX_DISPATCH_MAX_PAGES 0x{:x}u", gex_abi::DISPATCH_MAX_PAGES);
    let _ = writeln!(w, "#define GEX_DISPATCH_SHIFT {}u", gex_abi::DISPATCH_SHIFT);
    let _ = writeln!(w, "#define GEX_DISPATCH_TABLES {}u", gex_abi::DISPATCH_TABLES);
    let _ = writeln!(w, "#define GEX_DISPATCH_SLOT_BITS {}u", gex_abi::DISPATCH_SLOT_BITS);
    let _ = writeln!(w, "#define GEX_CACHE_OP_SLOT_CONFLICT {}", gex_abi::cache_op::SLOT_CONFLICT);
    let _ = writeln!(w, "#define GEX_CACHE_OP_SPLIT_LOCK {}", gex_abi::cache_op::SPLIT_LOCK);
    let _ = writeln!(w, "#define GEX_CACHE_OP_LOW_ACCESS {}", gex_abi::cache_op::LOW_ACCESS);
    let _ = writeln!(w, "#define GEX_GUEST_FLOOR 0x{:x}u", gex_abi::GUEST_FLOOR);
    let _ = writeln!(w, "#define GEX_SPLIT_LOCK 0x{:x}u", gex_abi::SPLIT_LOCK);
    let _ = writeln!(w, "#define GEX_PATCHED_PAGES 0x{:x}u", gex_abi::PATCHED_PAGES);
    let _ = writeln!(w, "#define GEX_NEST_EXITS 0x{:x}u", gex_abi::NEST_EXITS);
    let _ = writeln!(w, "#define GEX_BODY_LIMIT 0x{:x}u", gex_abi::BODY_LIMIT);
    let _ = writeln!(w);

    // The context. Every named offset, then the per-register helpers.
    let offs: &[(&str, usize)] = &[
        ("X", ctx::X),
        ("SP", ctx::SP),
        ("PC", ctx::PC),
        ("NZCV", ctx::NZCV),
        ("NF", ctx::NF),
        ("ZF", ctx::ZF),
        ("CF", ctx::CF),
        ("VF", ctx::VF),
        ("PF", ctx::PF),
        ("AF", ctx::AF),
        ("DF", ctx::DF),
        ("TPIDR", ctx::TPIDR),
        ("TPIDRRO", ctx::TPIDRRO),
        ("MON_ADDR", ctx::MON_ADDR),
        ("MON_VALUE", ctx::MON_VALUE),
        ("MON_SIZE", ctx::MON_SIZE),
        ("FPCR", ctx::FPCR),
        ("FPSR", ctx::FPSR),
        ("MXCSR", ctx::MXCSR),
        ("INTERRUPT", ctx::INTERRUPT),
        ("SAFEPOINT_COUNTER", ctx::SAFEPOINT_COUNTER),
        ("TID", ctx::TID),
        ("LAST_TARGET", ctx::LAST_TARGET),
        ("LAST_SOURCE", ctx::LAST_SOURCE),
        ("LAST_SYSCALL", ctx::LAST_SYSCALL),
        ("V", ctx::V),
        ("X87", ctx::X87),
        ("X87_TOP", ctx::X87_TOP),
        ("X87_CW", ctx::X87_CW),
        ("X87_SW", ctx::X87_SW),
        ("X87_TAGS", ctx::X87_TAGS),
        ("X87_TMP", ctx::X87_TMP),
        ("SCRATCH", ctx::SCRATCH),
        ("SIZE", ctx::SIZE),
    ];
    for (name, off) in offs {
        let _ = writeln!(w, "#define GEX_CTX_{name} {off}u");
    }
    let _ = writeln!(w, "#define GEX_CTX_XN(n) (GEX_CTX_X + 8u * (n))");
    let _ = writeln!(w, "#define GEX_CTX_VN(n) (GEX_CTX_V + 16u * (n))\n");

    w.push_str(BODY_TYPES);

    // Host imports, with the signatures `ModuleBuilder` declares.
    let m = IMPORT_MODULE;
    let decl = |w: &mut String, name: &str, ret: &str, c: &str, params: &str| {
        let _ = writeln!(
            w,
            "__attribute__((import_module(\"{m}\"), import_name(\"{name}\"))) {ret} {c}({params});"
        );
    };
    decl(w, imports::SYSCALL, "void", "gex_syscall", "int ctx, int64_t pc");
    decl(w, imports::DISPATCH_MISS, "int32_t", "gex_dispatch_miss", "int ctx, int64_t pc");
    decl(w, imports::ILLEGAL, "void", "gex_illegal", "int ctx, int64_t pc, int32_t raw");
    decl(w, imports::BREAKPOINT, "void", "gex_breakpoint", "int ctx, int64_t pc, int32_t imm");
    decl(w, imports::SYSREG_READ, "int64_t", "gex_sysreg_read", "int ctx, int64_t pc, int32_t reg");
    decl(w, imports::SYSREG_WRITE, "void", "gex_sysreg_write", "int ctx, int64_t pc, int32_t reg, int64_t v");
    decl(w, imports::CACHE_OP, "void", "gex_cache_op", "int ctx, int64_t pc, int32_t op, int64_t addr");
    decl(w, imports::FMA, "int64_t", "gex_fma", "int ctx, int64_t a, int64_t b, int64_t c, int32_t dbl");
    decl(w, imports::SAFEPOINT, "void", "gex_safepoint", "int ctx, int64_t pc");
    decl(
        w,
        imports::X87,
        "int64_t",
        "gex_x87",
        "int ctx, int32_t op, int64_t a_sig, int32_t a_se, int64_t b_sig, int32_t b_se, int32_t cw",
    );
    let _ = writeln!(
        w,
        "/* Tail-called with ctx.LAST_TARGET holding the target; the splice replaces\n   \
         it with tier-1's dispatch path. */\n\
         __attribute__((import_module(\"{}\"), import_name(\"{}\"))) void gexc_dispatch(int ctx);\n",
        crate::splice::DISPATCH_MODULE,
        crate::splice::DISPATCH_NAME
    );

    let _ = writeln!(w, "#define GEX_FMA_SPLIT {:?}", gex_emit::fma::SPLIT);
    let _ = writeln!(w, "#define GEX_FMA_SAFE_LO {}ull", gex_emit::fma::SAFE_LO);
    let _ = writeln!(w, "#define GEX_FMA_SAFE_HI {}ull", gex_emit::fma::SAFE_HI);
    w.push_str(BODY_HELPERS);
    w.push_str(X87_HELPERS);
    w.push_str("#endif\n");
    h
}

/// The x87 helpers, `Stmt::X87`'s lowering (see `emit.rs`).
const X87_HELPERS: &str = include_str!("../runtime/x87.h");

const BODY_TYPES: &str = r#"
/* Unaligned, alias-everything views of guest memory: a guest access is a
 * plain C access through one of these (guest VA == linear-memory offset ==
 * wasm32 C pointer). */
typedef uint8_t __attribute__((aligned(1), may_alias)) gex_u8;
typedef uint16_t __attribute__((aligned(1), may_alias)) gex_u16;
typedef uint32_t __attribute__((aligned(1), may_alias)) gex_u32;
typedef uint64_t __attribute__((aligned(1), may_alias)) gex_u64;
typedef int8_t __attribute__((aligned(1), may_alias)) gex_i8;
typedef int16_t __attribute__((aligned(1), may_alias)) gex_i16;
typedef int32_t __attribute__((aligned(1), may_alias)) gex_i32;
/* Naturally aligned views, for the atomics (a misaligned wasm atomic traps,
 * exactly as tier-1's does). */
typedef uint8_t __attribute__((may_alias)) gex_a8;
typedef uint16_t __attribute__((may_alias)) gex_a16;
typedef uint32_t __attribute__((may_alias)) gex_a32;
typedef uint64_t __attribute__((may_alias)) gex_a64;

#define GEX_CTXP(ctx) ((char *)(uintptr_t)(uint32_t)(ctx))
#define GEX_C8(o) (*(gex_u8 *)(GEX_CTXP(ctx) + (o)))
#define GEX_C16(o) (*(gex_u16 *)(GEX_CTXP(ctx) + (o)))
#define GEX_C32(o) (*(gex_u32 *)(GEX_CTXP(ctx) + (o)))
#define GEX_C64(o) (*(gex_u64 *)(GEX_CTXP(ctx) + (o)))
#define GEX_CV(o) wasm_v128_load(GEX_CTXP(ctx) + (o))
#define GEX_CV_SET(o, v) wasm_v128_store(GEX_CTXP(ctx) + (o), (v))
#define GEX_MUSTTAIL __attribute__((musttail))

"#;

const BODY_HELPERS: &str = r#"
#define GEX_INLINE static inline __attribute__((always_inline))

/* tier-1's guard: an effective address that does not fit below GUEST_LIMIT is
 * steered to POISON_ADDR, which traps. For accesses with no static offset. */
GEX_INLINE uint32_t gex_g(uint64_t a) {
    return a < GEX_GUEST_LIMIT ? (uint32_t)a : GEX_POISON_ADDR;
}
/* The same guard for a base that carries a static offset of at most 0xffff.
 * Steering to GUEST_LIMIT keeps base + offset + size below 2^32 and above the
 * memory's end, so the access traps whether or not clang folds the offset
 * into the memarg (from POISON_ADDR an unfolded add would wrap to low memory). */
GEX_INLINE char *gex_gb(uint64_t a) {
    return (char *)(uintptr_t)(a < GEX_GUEST_LIMIT ? (uint32_t)a : (uint32_t)GEX_GUEST_LIMIT);
}
/* A static offset above 0xffff (AArch64 only): tier-1 adds it in the memarg,
 * a 33-bit sum that traps past 2^32. Emulated exactly. */
GEX_INLINE char *gex_g33(uint64_t base, uint64_t off) {
    uint64_t e = (uint64_t)gex_g(base) + off;
    return (char *)(uintptr_t)(e < 0x100000000ull ? (uint32_t)e : GEX_POISON_ADDR);
}
#define GEX_P(a) ((char *)(uintptr_t)(a))

/* An optimisation barrier on one value: what the compiler knows about it stops
 * here. Used where an idiom would otherwise become a libcall. */
GEX_INLINE uint64_t gex_opaque64(uint64_t x) {
    __asm__("" : "+r"(x));
    return x;
}

GEX_INLINE float gex_f32(uint32_t b) { return __builtin_bit_cast(float, b); }
GEX_INLINE double gex_f64(uint64_t b) { return __builtin_bit_cast(double, b); }
GEX_INLINE uint32_t gex_b32(float f) { return __builtin_bit_cast(uint32_t, f); }
GEX_INLINE uint64_t gex_b64(double f) { return __builtin_bit_cast(uint64_t, f); }

/* Single-precision FMA, tier-1's `emit_fmaf` step for step: the product is
 * exact in f64, round-to-odd on the sum. Operands are f32 bits in the low
 * half; the result is zero-extended f32 bits, as the import returns. */
GEX_INLINE uint64_t gex_fmaf(uint64_t a, uint64_t b, uint64_t c) {
    double p = (double)gex_f32((uint32_t)a) * (double)gex_f32((uint32_t)b);
    double cc = (double)gex_f32((uint32_t)c);
    double s = p + cc;
    double bb = s - p;
    double t = (p - (s - bb)) + (cc - bb);
    double r = s;
    if ((t != 0.0) & ((gex_b64(s) & 1) == 0))
        r = gex_f64(gex_b64(s) + (((t > 0.0) == (s > 0.0)) ? 1ull : (uint64_t)-1));
    return (uint64_t)gex_b32((float)r);
}

GEX_INLINE int gex_fma_fast(double v) {
    uint64_t e = (gex_b64(v) >> 52) & 0x7ff;
    return ((e >= GEX_FMA_SAFE_LO) & (e <= GEX_FMA_SAFE_HI)) | (v == 0.0);
}

/* Double-precision FMA: Dekker behind the exponent guard, the import outside
 * it -- tier-1's `emit_fma64`. */
GEX_INLINE uint64_t gex_fma64(int ctx, uint64_t ab, uint64_t bb_, uint64_t cb, uint32_t dbl) {
    double a = gex_f64(ab), b = gex_f64(bb_), c = gex_f64(cb);
    if (gex_fma_fast(a) & gex_fma_fast(b) & gex_fma_fast(c)) {
        double p = a * b;
        double ta = a * GEX_FMA_SPLIT;
        double ah = ta - (ta - a);
        double al = a - ah;
        double tb = b * GEX_FMA_SPLIT;
        double bh = tb - (tb - b);
        double bl = b - bh;
        double e = (((ah * bh - p) + ah * bl) + al * bh) + al * bl;
        double s = p + c;
        double t0 = s - p;
        double t = (p - (s - t0)) + (c - t0);
        return gex_b64(s + (t + e));
    }
    return (uint64_t)gex_fma(ctx, (int64_t)ab, (int64_t)bb_, (int64_t)cb, (int32_t)dbl);
}

/* Whether the code page holding guest address `a` was rewritten after its
   unit was installed (gex_abi::PATCHED_PAGES): a constant address, one load. */
#define GEX_PATCHED(a) \
    ((*(volatile uint8_t *)GEX_P(GEX_PATCHED_PAGES + (uint32_t)((a) >> 15)) >> (uint32_t)(((a) >> 12) & 7u)) & 1u)

/* Old value of a compare-and-swap, at each width. */
#define GEX_CAS(T, p, e, r) __sync_val_compare_and_swap((T *)(p), (e), (r))

/* An x86 locked access that is not naturally aligned, atomically, exactly as
   tier-1 does it (gex-emit's emit_misaligned_atomic), so the two tiers stay
   atomic against each other: inside one aligned 8-byte word, a
   compare-exchange loop on that word; across two, under the lock word at
   GEX_SPLIT_LOCK (shared with tier-1), the first such access reported.
   `op`: 0 compare-exchange (a expected, b replacement), 1 add, 2 sub, 3 and,
   4 or, 5 xor, 6 exchange (a the operand). Returns the old value. */
#define GEX_LK_CAS 0
#define GEX_LK_ADD 1
#define GEX_LK_SUB 2
#define GEX_LK_AND 3
#define GEX_LK_OR 4
#define GEX_LK_XOR 5
#define GEX_LK_XCHG 6
static inline uint64_t gex_lk_apply(int op, uint64_t old, uint64_t a, uint64_t b) {
    switch (op) {
    case GEX_LK_CAS: return b;
    case GEX_LK_ADD: return old + a;
    case GEX_LK_SUB: return old - a;
    case GEX_LK_AND: return old & a;
    case GEX_LK_OR: return old | a;
    case GEX_LK_XOR: return old ^ a;
    default: return a;
    }
}
static __attribute__((noinline)) uint64_t gex_locked_misaligned(int ctx, int64_t pc, uint32_t ea, uint32_t bytes,
                                                                int op, uint64_t a, uint64_t b) {
    uint64_t field = bytes >= 8 ? ~0ull : ((1ull << (bytes * 8)) - 1);
    if ((ea & 7u) + bytes <= 8u) {
        uint32_t wa = ea & ~7u;
        uint32_t sh = (ea & 7u) * 8u;
        for (;;) {
            uint64_t w = __atomic_load_n((gex_a64 *)GEX_P(wa), __ATOMIC_SEQ_CST);
            uint64_t f = (w >> sh) & field;
            if (op == GEX_LK_CAS && f != (a & field))
                return f;
            uint64_t nw = ((gex_lk_apply(op, f, a, b) & field) << sh) | (w & ~(field << sh));
            if (GEX_CAS(gex_a64, GEX_P(wa), w, nw) == w)
                return f;
        }
    }
    if (*(volatile uint32_t *)GEX_P(GEX_SPLIT_LOCK + 4u) == 0) {
        *(volatile uint32_t *)GEX_P(GEX_SPLIT_LOCK + 4u) = 1;
        gex_cache_op(ctx, pc, GEX_CACHE_OP_SPLIT_LOCK, (int64_t)ea);
    }
    while (GEX_CAS(gex_a32, GEX_P(GEX_SPLIT_LOCK), 0u, 1u) != 0u) {
    }
    uint64_t old = bytes == 8 ? *(gex_u64 *)GEX_P(ea) : bytes == 4 ? *(gex_u32 *)GEX_P(ea) : *(gex_u16 *)GEX_P(ea);
    if (op != GEX_LK_CAS || old == (a & field)) {
        uint64_t nv = gex_lk_apply(op, old, a, b) & field;
        if (bytes == 8)
            *(gex_u64 *)GEX_P(ea) = nv;
        else if (bytes == 4)
            *(gex_u32 *)GEX_P(ea) = (uint32_t)nv;
        else
            *(gex_u16 *)GEX_P(ea) = (uint16_t)nv;
    }
    __atomic_store_n((gex_a32 *)GEX_P(GEX_SPLIT_LOCK), 0u, __ATOMIC_SEQ_CST);
    return old;
}
"#;

